import { mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const sourceDirectory = path.dirname(fileURLToPath(import.meta.url));
const outputDirectory = path.resolve(sourceDirectory, "..", "final");

const assets = [
  ["02-how-it-works.svg", "02-how-it-works.png"],
  ["03-who-does-what.svg", "03-who-does-what.png"],
  ["06-webmcp-architecture.svg", "06-webmcp-architecture.png"],
];

await mkdir(outputDirectory, { recursive: true });

for (const [sourceName, outputName] of assets) {
  const sourcePath = path.join(sourceDirectory, sourceName);
  const outputPath = path.join(outputDirectory, outputName);

  await sharp(sourcePath, { density: 96 })
    .resize(1500, 1000, { fit: "fill" })
    .png({ compressionLevel: 9, palette: false })
    .withMetadata({ density: 96 })
    .toFile(outputPath);

  const metadata = await sharp(outputPath).metadata();
  if (metadata.width !== 1500 || metadata.height !== 1000 || metadata.format !== "png") {
    throw new Error(
      `${outputName} rendered as ${metadata.width}x${metadata.height} ${metadata.format}; expected 1500x1000 PNG.`,
    );
  }

  console.log(`Rendered ${outputName} (${metadata.width}x${metadata.height})`);
}

console.log("Asset 01 is generated by build-hero-controlled-redesign.mjs.");
console.log("Assets 04 and 05 are generated from real screenshots and promoted by freeze-media-package.mjs.");
